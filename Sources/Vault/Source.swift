import Foundation

/// The contract every vault signs. 🤝
///
/// Three sources, three completely different mechanics: a signed-in CLI, a file
/// on disk read through somebody else's binary, and a system API with its own
/// consent dialogs. They agree on three things and nothing else, so those three
/// things are the protocol.
///
/// **Indexing is slow and happens off the main thread. Fetching is fast and
/// happens on it.** `index()` shells out, decrypts, or walks a keychain, and
/// takes anything from milliseconds to a second; the menu bar shows a spinner
/// while it runs. `secret(for:)` is on the path between a keystroke and a
/// paste, so it has a budget of a few tens of milliseconds and is allowed to
/// block the main thread inside it.
///
/// The trap: `state` is read every time the menu opens, so it must not itself
/// go and ask an expensive question. It reports what the last `index()` found,
/// plus whatever is free to check (does a file exist, is a binary installed).
protocol Source: AnyObject {

    var kind: SourceKind { get }

    /// Cheap, synchronous, safe to call from `menuWillOpen`.
    var state: SourceState { get }

    /// Everything this source is willing to list. Called off the main thread.
    /// Throwing means the source is unreachable, not that it is empty.
    func index() throws -> [Item]

    /// The username and password for one item, read now.
    func secret(for item: Item) throws -> Credential

    /// The current one-time code, when the entry has a seed for one.
    func totp(for item: Item) throws -> String

    /// Where a new entry could go: 1Password's vaults, KeePassXC's groups.
    /// Empty means this source is read only, and the menu says so.
    var destinations: [String] { get }

    /// Make a new login. The password is generated by the vault itself, never
    /// here, so it never crosses a process boundary as an argument and Sesam
    /// never has to be trusted with a random number generator.
    func create(_ draft: Draft) throws -> Item

    /// Replace one entry's password with a newly generated one.
    func regenerate(for item: Item) throws

    /// Forget whatever was being held open. Called on screen lock, on sleep,
    /// on the idle timer and on `sesam lock`. Must be safe to call twice, and
    /// safe to call on a source that was never unlocked.
    func lock()
}

/// What somebody typed into the new item sheet. Not a secret: the password is
/// the vault's business, which is the point.
struct Draft {
    var title: String
    var username: String
    var url: String
    /// A vault name for 1Password, a group path for KeePassXC, empty for the
    /// default of either.
    var destination: String
}

extension Source {
    /// Most entries in most vaults have no second factor, and one source (the
    /// login keychain) has no notion of one at all. Saying so is the default,
    /// so that only the two sources that can answer have to write anything.
    func totp(for item: Item) throws -> String {
        throw VaultError("no one-time code in this entry", routine: true)
    }

    /// Read only unless a source says otherwise. The login keychain is the one
    /// that stays this way: it is where applications keep their own tokens,
    /// and a launcher adding logins to it would be putting them somewhere
    /// nothing else knows to look.
    var destinations: [String] { [] }

    func create(_ draft: Draft) throws -> Item {
        throw VaultError("Sesam does not write to \(kind.label)", routine: true)
    }

    func regenerate(for item: Item) throws {
        throw VaultError("Sesam does not write to \(kind.label)", routine: true)
    }
}

/// Where a source stands, in the words the menu uses.
enum SourceState: Equatable {
    /// Indexed and answering, with the number of items it found.
    case ready(Int)
    /// Configured and reachable, but the key is not in hand: KeePassXC before
    /// the master password is typed, 1Password before `op` is signed in.
    case locked
    /// Switched off in the menu.
    case off
    /// Nothing to talk to: no database chosen, `op` not installed.
    case notConfigured(String)
    /// It was asked and it refused. Carries the reason, verbatim.
    case failed(String)

    var dot: String {
        switch self {
        case .ready:          return "●"
        case .locked:         return "◐"
        case .off:            return "○"
        case .notConfigured:  return "○"
        case .failed:         return "▲"
        }
    }

    var line: String {
        switch self {
        case .ready(let n):         return "\(n) items"
        case .locked:               return "locked"
        case .off:                  return "off"
        case .notConfigured(let s): return s
        case .failed(let s):        return s
        }
    }
}

/// The one error type any source raises. The message is shown to the user, so
/// it is written for one.
///
/// `routine` is the difference between "this entry has no one-time code" and
/// "the keychain refused". The first is an ordinary answer to an ordinary
/// question and belongs in the row somebody is looking at; the second is a
/// failure and deserves an alert. Putting a modal dialog in front of the first
/// teaches people that the key they pressed is dangerous, when all it did was
/// ask a question with a boring answer.
struct VaultError: LocalizedError {
    let message: String
    let routine: Bool
    init(_ message: String, routine: Bool = false) {
        self.message = message
        self.routine = routine
    }
    var errorDescription: String? { message }
}
