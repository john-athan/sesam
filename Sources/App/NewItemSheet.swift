import Cocoa

/// The only form in the app. 📝
///
/// Four controls, because a new login needs four answers and the fifth, the
/// password, is not Sesam's to give: the vault generates it. That is the whole
/// reason this sheet is as small as it is.
///
/// It is an `NSAlert` with an accessory view rather than a window of its own.
/// A window would need a controller, a nib or a layout pass, focus handling and
/// a close button, to hold three text fields that are on screen for eight
/// seconds.
///
/// The trap: an accessory view has to be given an explicit frame and its
/// controls need `nextKeyView` wired by hand, or Tab does nothing and the sheet
/// feels broken in the first second somebody uses it.
enum NewItemSheet {

    /// Returns where to write and what to write, or nil if it was cancelled.
    static func ask(title prefill: String) -> (SourceKind, Draft)? {
        let destinations = Vault.shared.destinations()
        guard !destinations.isEmpty else {
            let alert = NSAlert()
            alert.messageText = "Nowhere to save it yet"
            alert.informativeText = "1Password needs op to be signed in, and KeePassXC needs to "
                                  + "be unlocked, before Sesam can add anything to them. The "
                                  + "login keychain is read only."
            alert.runModal()
            return nil
        }

        let alert = NSAlert()
        alert.messageText = "New login"
        alert.informativeText = "The password is generated by the vault you choose, and copied "
                              + "to your clipboard."
        alert.addButton(withTitle: "Create")
        alert.addButton(withTitle: "Cancel")

        let title = field("Title", prefill)
        let username = field("Username", "")
        let url = field("URL", "")
        let where_ = NSPopUpButton(frame: NSRect(x: 0, y: 0, width: 320, height: 25))
        for (kind, name) in destinations { where_.addItem(withTitle: label(kind, name)) }

        let view = NSView(frame: NSRect(x: 0, y: 0, width: 320, height: 121))
        for (index, control) in [title, username, url, where_].enumerated() {
            control.frame.origin = NSPoint(x: 0, y: CGFloat(3 - index) * 32)
            view.addSubview(control)
        }
        title.nextKeyView = username
        username.nextKeyView = url
        url.nextKeyView = where_

        alert.accessoryView = view
        alert.window.initialFirstResponder = title

        NSApp.activate(ignoringOtherApps: true)
        guard alert.runModal() == .alertFirstButtonReturn else { return nil }

        let name = title.stringValue.trimmingCharacters(in: .whitespaces)
        guard !name.isEmpty else { return nil }
        let (kind, destination) = destinations[where_.indexOfSelectedItem]
        return (kind, Draft(title: name,
                            username: username.stringValue.trimmingCharacters(in: .whitespaces),
                            url: url.stringValue.trimmingCharacters(in: .whitespaces),
                            destination: destination))
    }

    private static func field(_ placeholder: String, _ value: String) -> NSTextField {
        let field = NSTextField(frame: NSRect(x: 0, y: 0, width: 320, height: 24))
        field.placeholderString = placeholder
        field.stringValue = value
        return field
    }

    private static func label(_ kind: SourceKind, _ destination: String) -> String {
        destination.isEmpty ? kind.label : "\(kind.label): \(destination)"
    }
}
